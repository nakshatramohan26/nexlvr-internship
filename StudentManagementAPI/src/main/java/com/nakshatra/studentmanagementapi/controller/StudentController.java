package com.nakshatra.studentmanagementapi.controller;

import com.nakshatra.studentmanagementapi.exception.ErrorResponse;
import com.nakshatra.studentmanagementapi.model.Student;
import com.nakshatra.studentmanagementapi.service.StudentService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.media.ArraySchema;
import io.swagger.v3.oas.annotations.media.Content;
import io.swagger.v3.oas.annotations.media.Schema;
import io.swagger.v3.oas.annotations.responses.ApiResponse;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import java.net.URI;
import java.util.List;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.support.ServletUriComponentsBuilder;

/**
 * REST controller: receives HTTP requests, delegates the work to StudentService and
 * returns the HTTP status code + JSON body. It contains no business logic itself.
 */
@RestController
@RequestMapping("/api/students")
@Tag(name = "Students", description = "Create, read, update and delete student records")
public class StudentController {

    private final StudentService studentService;

    // Constructor injection: Spring passes in the StudentService bean.
    public StudentController(StudentService studentService) {
        this.studentService = studentService;
    }

    @PostMapping
    @Operation(summary = "Create a student",
            description = "Creates a new student. The id is generated by the server. "
                    + "Returns 201 Created with a Location header pointing to the new student.")
    @ApiResponse(responseCode = "201", description = "Student created",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "Validation failed or body is malformed",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> createStudent(@Valid @RequestBody Student student) {
        Student created = studentService.create(student);
        // Location: http://localhost:8080/api/students/{id}
        URI location = ServletUriComponentsBuilder.fromCurrentRequest()
                .path("/{id}")
                .buildAndExpand(created.getId())
                .toUri();
        return ResponseEntity.created(location).body(created);
    }

    @GetMapping
    @Operation(summary = "Get all students",
            description = "Returns every student, ordered by id. Returns an empty list when there are none.")
    @ApiResponse(responseCode = "200", description = "List of students (possibly empty)",
            content = @Content(array = @ArraySchema(schema = @Schema(implementation = Student.class))))
    public ResponseEntity<List<Student>> getAllStudents() {
        return ResponseEntity.ok(studentService.findAll());
    }

    @GetMapping("/{id}")
    @Operation(summary = "Get a student by id", description = "Returns the student with the given id.")
    @ApiResponse(responseCode = "200", description = "Student found",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "The id is not a whole number",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> getStudentById(
            @Parameter(description = "Id of the student", example = "1") @PathVariable Long id) {
        return ResponseEntity.ok(studentService.findById(id));
    }

    @PutMapping("/{id}")
    @Operation(summary = "Update a student",
            description = "Replaces all fields (name, email, department, year) of an existing student. "
                    + "The id in the URL is used; an id inside the body is ignored.")
    @ApiResponse(responseCode = "200", description = "Student updated",
            content = @Content(schema = @Schema(implementation = Student.class)))
    @ApiResponse(responseCode = "400", description = "Validation failed, malformed body or id is not a number",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Student> updateStudent(
            @Parameter(description = "Id of the student to update", example = "1") @PathVariable Long id,
            @Valid @RequestBody Student student) {
        return ResponseEntity.ok(studentService.update(id, student));
    }

    @DeleteMapping("/{id}")
    @Operation(summary = "Delete a student", description = "Deletes the student with the given id.")
    @ApiResponse(responseCode = "204", description = "Student deleted (no response body)")
    @ApiResponse(responseCode = "400", description = "The id is not a whole number",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    @ApiResponse(responseCode = "404", description = "No student with this id",
            content = @Content(schema = @Schema(implementation = ErrorResponse.class)))
    public ResponseEntity<Void> deleteStudent(
            @Parameter(description = "Id of the student to delete", example = "1") @PathVariable Long id) {
        studentService.delete(id);
        return ResponseEntity.noContent().build();
    }
}

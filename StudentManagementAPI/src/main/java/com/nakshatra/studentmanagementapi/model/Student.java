package com.nakshatra.studentmanagementapi.model;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.Email;
import jakarta.validation.constraints.Max;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;

/**
 * A student record. The same class is used as the JSON request body and response body.
 *
 * Validation rules (checked automatically because the controller uses @Valid):
 *  - name, email, department: must not be null, empty or only spaces
 *  - email: must look like an email address
 *  - year: required, whole number from 1 to 4 (B.Tech years)
 *  - id: created by the server; any id sent by the client is ignored
 */
@Schema(description = "A student record")
public class Student {

    @Schema(description = "Unique id generated by the server (any value sent by the client is ignored)",
            example = "1", accessMode = Schema.AccessMode.READ_ONLY)
    private Long id;

    @NotBlank(message = "Name must not be blank")
    @Size(max = 100, message = "Name must be at most 100 characters")
    @Schema(description = "Full name of the student", example = "Nakshatra M")
    private String name;

    @NotBlank(message = "Email must not be blank")
    @Email(message = "Email must be a valid email address")
    @Size(max = 254, message = "Email must be at most 254 characters")
    @Schema(description = "Email address of the student", example = "nakshatra@example.com")
    private String email;

    @NotBlank(message = "Department must not be blank")
    @Size(max = 100, message = "Department must be at most 100 characters")
    @Schema(description = "Department the student belongs to", example = "Information Technology")
    private String department;

    @NotNull(message = "Year is required")
    @Min(value = 1, message = "Year must be between 1 and 4")
    @Max(value = 4, message = "Year must be between 1 and 4")
    @Schema(description = "Year of study (1 to 4)", example = "2")
    private Integer year;

    /** Needed by Jackson (the JSON library) to create an object from a request body. */
    public Student() {
    }

    public Student(String name, String email, String department, Integer year) {
        this.name = name;
        this.email = email;
        this.department = department;
        this.year = year;
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getDepartment() {
        return department;
    }

    public void setDepartment(String department) {
        this.department = department;
    }

    public Integer getYear() {
        return year;
    }

    public void setYear(Integer year) {
        this.year = year;
    }
}
